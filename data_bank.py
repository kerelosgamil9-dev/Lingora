def level_count():
    return len(LEVELS)


def get_level(n):
    """Return the level dict for level number n (1-based)."""
    if 1 <= n <= len(LEVELS):
        return LEVELS[n - 1]
    return None


def total_words():
    return sum(len(l['words']) for l in LEVELS)


